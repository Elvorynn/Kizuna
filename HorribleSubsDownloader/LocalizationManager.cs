        private static AppLanguage _current = AppLanguage.English;

        public static AppLanguage Current => _current;

        public static void SetLanguage(AppLanguage lang) => _current = lang;

        public static void SetLanguage(string lang)
        {
            switch (lang)
            {
                case "German":   _current = AppLanguage.German;   break;
                case "French":   _current = AppLanguage.French;   break;
                case "Spanish":  _current = AppLanguage.Spanish;  break;
                case "Japanese": _current = AppLanguage.Japanese; break;
                default:         _current = AppLanguage.English;  break;
            }
        }

        public static string Get(string key)
        {
            if (_strings.TryGetValue(_current, out var dict) && dict.TryGetValue(key, out var val))
                return val;
            if (_strings.TryGetValue(AppLanguage.English, out var en) && en.TryGetValue(key, out var enVal))
                return enVal;
            return key;
        }

